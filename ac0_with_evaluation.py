# ── Section 1: Utilities ─────────────────────────────────────────────────────

def px_to_mm(val):
    """Convert a pixel-space value to millimetres."""
    return val * SCALE


def angle_wrap_error(a, b):
    """
    Absolute angular error with wrap-around (period = pi for ellipse axis).
    An ellipse at 0 rad and pi rad are identical — the axis is symmetric.
    Returns a value between 0 and pi/2.
    """
    diff = abs(a - b) % math.pi
    return min(diff, math.pi - diff)


# ── Section 2: Ground truth loading ─────────────────────────────────────────

def load_ground_truth(json_path):
    """
    Load the annotations JSON file.
    Returns dict: image_id (int) → {cx, cy, a, b, theta, num_hits}
    All values are already in mm as stored in the JSON.
    """
    with open(json_path) as f:
        data = json.load(f)
    gt = {}
    for ann in data["annotations"]:
        gt[int(ann["image_id"])] = {
            "cx":       ann["cx"],
            "cy":       ann["cy"],
            "a":        ann["a"],
            "b":        ann["b"],
            "theta":    ann["theta"],
            "num_hits": ann["num_hits"],
        }
    return gt


# ── Section 3: Image loading ─────────────────────────────────────────────────

def load_points_with_intensity(image_path):
    """
    Load a 20x20 greyscale image and return intensity-weighted pixel list.

    Returns
    -------
    points : list of (x_px, y_px, normalised_intensity)
        Only non-zero pixels are included. Intensity normalised to [0, 1].
    img_np : numpy array of the raw image (for visualisation)
    w, h   : image width and height in pixels
    """
    img_pil = Image.open(image_path).convert("L")
    img_np  = np.array(img_pil, dtype=np.float32)

    h, w    = img_np.shape
    max_val = img_np.max()
    if max_val == 0:
        max_val = 1.0

    points = []
    for row in range(h):
        for col in range(w):
            pixel = img_np[row, col]
            if pixel > 0:
                points.append((float(col), float(row), pixel / max_val))

    return points, img_np, w, h


# ── Section 4: IoU computation ───────────────────────────────────────────────

def ellipse_mask(cx_mm, cy_mm, a_mm, b_mm, theta_rad,
                 render_size=IOU_RENDER_SZ):
    """Render a filled ellipse in mm-space onto a binary mask."""
    mask  = np.zeros((render_size, render_size), dtype=np.uint8)
    sc    = render_size / SPACE_SIZE_MM
    cx_r  = int(round(cx_mm * sc))
    cy_r  = int(round(cy_mm * sc))
    a_r   = max(1, int(round(a_mm * sc)))
    b_r   = max(1, int(round(b_mm * sc)))
    angle = math.degrees(theta_rad)
    cv2.ellipse(mask, (cx_r, cy_r), (a_r, b_r),
                angle, 0, 360, color=1, thickness=-1)
    return mask


def compute_iou(det_mm, gt_mm):
    """
    Compute Intersection over Union between detected and ground truth ellipses.
    Both ellipses are rendered as filled masks on a 400x400 mm-space grid.
    Returns a float in [0, 1]. Pass threshold = IOU_THRESHOLD (0.70).
    """
    m1 = ellipse_mask(det_mm["cx"], det_mm["cy"],
                      det_mm["a"],  det_mm["b"],  det_mm["theta"])
    m2 = ellipse_mask(gt_mm["cx"],  gt_mm["cy"],
                      gt_mm["a"],   gt_mm["b"],   gt_mm["theta"])
    inter = np.sum((m1 == 1) & (m2 == 1))
    union = np.sum((m1 == 1) | (m2 == 1))
    return float(inter) / float(union) if union > 0 else 0.0


