def run_algorithm(points_with_intensity, width, height):
    """
    ACO-based ellipse detection.

    Parameters
    ----------
    points_with_intensity : list of (x, y, intensity) tuples
    width  : int  — image width  in pixels (20)
    height : int  — image height in pixels (20)

    Returns
    -------
    list : [cx_px, cy_px, a_px, b_px, theta_rad]
        Detected ellipse parameters in PIXEL coordinates.
    """
    if not points_with_intensity:
        return [width / 2, height / 2, width / 4, height / 4, 0.0]

    try:
        best = run_aco(points_with_intensity, width, height)

        # Ensure a >= b (swap axes, flip theta by 90° if needed)
        cx, cy, a, b, theta = best
        if b > a:
            a, b = b, a
            theta = theta + math.pi / 2

        # Final bounds clamp
        cx    = max(0.0,  min(float(width),       cx))
        cy    = max(0.0,  min(float(height),       cy))
        a     = max(0.5,  min(float(width) / 2,    a))
        b     = max(0.25, min(a,                   b))

        return [cx, cy, a, b, theta]

    except Exception:
        return [width / 2, height / 2, width / 4, height / 4, 0.0]


