def process_all_images(gt_dict, images_folder):
    """
    Run run_algorithm() on every image in the dataset.
    Returns a list of result dictionaries, one per image.
    """
    results   = []
    image_ids = sorted(gt_dict.keys())

    print(f"\n{'─' * 65}")
    print(f"  Processing {len(image_ids)} images ...")
    print(f"{'─' * 65}")

    for idx, img_id in enumerate(image_ids):
        img_path = os.path.join(images_folder, f"id_{img_id}.png")
        if not os.path.exists(img_path):
            print(f"  [WARNING] Image not found, skipping: {img_path}")
            continue

        t0 = time.time()

        # Load image as intensity-weighted pixel list
        pts, raw_img, w, h = load_points_with_intensity(img_path)

        # Call YOUR algorithm — returns [cx_px, cy_px, a_px, b_px, theta_rad]
        best_px = run_algorithm(pts, w, h)

        elapsed_ms = (time.time() - t0) * 1000.0

        # Convert detected parameters from pixel space to mm
        det_mm = {
            "cx":    px_to_mm(best_px[0]),
            "cy":    px_to_mm(best_px[1]),
            "a":     px_to_mm(best_px[2]),
            "b":     px_to_mm(best_px[3]),
            "theta": best_px[4],           # angle is dimensionless
        }

        gt = gt_dict[img_id]

        # Compute per-image errors
        err_cx    = abs(det_mm["cx"]    - gt["cx"])
        err_cy    = abs(det_mm["cy"]    - gt["cy"])
        err_a     = abs(det_mm["a"]     - gt["a"])
        err_b     = abs(det_mm["b"]     - gt["b"])
        err_theta = angle_wrap_error(det_mm["theta"], gt["theta"])

        iou    = compute_iou(det_mm, gt)
        passed = iou >= IOU_THRESHOLD

        results.append({
            "image_id":  img_id,
            "raw_img":   raw_img,
            "pts_px":    pts,
            "det_px":    best_px,
            "det_mm":    det_mm,
            "gt":        gt,
            "err_cx":    err_cx,
            "err_cy":    err_cy,
            "err_a":     err_a,
            "err_b":     err_b,
            "err_theta": err_theta,
            "iou":       iou,
            "passed":    passed,
            "time_ms":   elapsed_ms,
        })

        status = "PASS" if passed else "FAIL"
        print(f"  [{idx + 1:4d}/{len(image_ids)}]  id={img_id:4d}  "
              f"IoU={iou:.3f}  {status}  ({elapsed_ms:.0f} ms)  "
              f"det=({det_mm['cx']:.1f},{det_mm['cy']:.1f})mm  "
              f"gt=({gt['cx']:.1f},{gt['cy']:.1f})mm")

    return results


