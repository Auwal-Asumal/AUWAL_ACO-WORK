# ── ACO hyper-parameters ──────────────────────────────────────────────────────
N_ANTS     = 60    # colony size  (number of candidate solutions per iteration)
ARCHIVE_SZ = 20    # pheromone archive size (best solutions retained)
N_ITERS    = 20    # number of ACO generations
Q_BEST     = 10     # top-Q ants that update the archive each iteration
XI         = 0.5   # Gaussian spread factor — lower ⟹ faster convergence
W_RANK     = 1.0   # rank-weight exponent for archive sampling probability


# ── Search-space bounds (pixel coordinates) ───────────────────────────────────
BOUNDS = {
    #         min       max
    "cx":    (0.0,      20.0),
    "cy":    (0.0,      20.0),
    "a":     (1.0,      10.0),   # semi-major axis  ≥ 1 px
    "b":     (0.5,       9.0),   # semi-minor axis  < a enforced later
    "theta": (-math.pi/2, math.pi/2),
}

# Ordered list of parameter names (matches the 5-vector convention)
PARAM_NAMES = ["cx", "cy", "a", "b", "theta"]


def _point_to_ellipse_dist_sq(px, py, cx, cy, a, b, theta):
    """
    Squared algebraic distance from point (px, py) to the ellipse defined
    by [cx, cy, a, b, theta].  Uses the normalised algebraic form:

        F(x,y) = ((x'/ a)^2 + (y'/ b)^2 - 1)^2

    where (x', y') is the point rotated into the ellipse frame.
    This is O(1) per point and differentiable — ideal for fitness.
    """
    cos_t = math.cos(theta)
    sin_t = math.sin(theta)
    dx    = px - cx
    dy    = py - cy
    xr    =  dx * cos_t + dy * sin_t   # rotate into ellipse frame
    yr    = -dx * sin_t + dy * cos_t
    val   = (xr / (a + 1e-9)) ** 2 + (yr / (b + 1e-9)) ** 2 - 1.0
    return val * val


def _fitness(params, points_xy_w):
    """
    Evaluate a candidate ellipse against the weighted point cloud.

    params       : [cx, cy, a, b, theta]
    points_xy_w  : list of (x, y, weight)

    Returns a fitness score in (0, 1] — higher is better.
    Adds a penalty if semi-minor > semi-major (b > a).
    """
    cx, cy, a, b, theta = params

    # Enforce a ≥ b (swap silently so we don't penalise orientation flip)
    if b > a:
        a, b = b, a

    total_w  = 0.0
    total_wd = 0.0
    for (px, py, w) in points_xy_w:
        d2       = _point_to_ellipse_dist_sq(px, py, cx, cy, a, b, theta)
        total_w  += w
        total_wd += w * d2

    if total_w == 0:
        return 0.0

    mean_dist = total_wd / total_w
    return 1.0 / (1.0 + mean_dist)


def _clip(params):
    """Clip each parameter to its search-space bounds."""
    clipped = []
    for i, name in enumerate(PARAM_NAMES):
        lo, hi = BOUNDS[name]
        clipped.append(max(lo, min(hi, params[i])))
    return clipped


def _init_archive(points_xy_w, width, height, archive_size):
    """
    Seed the pheromone archive with random solutions, evaluated and sorted
    by fitness descending.  A few heuristic seeds are also injected:
      • weighted centroid of the point cloud → reasonable cx, cy guess
      • two random scales in [1, 5] px for a, b
    """
    # Weighted centroid seed
    total_w = sum(w for _, _, w in points_xy_w)
    if total_w > 0:
        cx0 = sum(x * w for x, y, w in points_xy_w) / total_w
        cy0 = sum(y * w for x, y, w in points_xy_w) / total_w
    else:
        cx0, cy0 = width / 2, height / 2

    archive = []

    # Inject centroid-based heuristic seeds
    for _ in range(max(2, archive_size // 5)):
        a0 = random.uniform(2.0, 6.0)
        b0 = random.uniform(1.0, a0)
        t0 = random.uniform(-math.pi / 2, math.pi / 2)
        candidate = _clip([cx0, cy0, a0, b0, t0])
        archive.append((candidate, _fitness(candidate, points_xy_w)))

    # Fill remainder with random candidates
    while len(archive) < archive_size:
        candidate = _clip([
            random.uniform(*BOUNDS["cx"]),
            random.uniform(*BOUNDS["cy"]),
            random.uniform(*BOUNDS["a"]),
            random.uniform(*BOUNDS["b"]),
            random.uniform(*BOUNDS["theta"]),
        ])
        archive.append((candidate, _fitness(candidate, points_xy_w)))

    archive.sort(key=lambda x: x[1], reverse=True)
    return archive


def _archive_weights(archive_size):
    """
    Rank-based selection probabilities for the archive.
    Rank 1 (best) gets the highest weight.
    w_k ∝ exp(-(k-1)^2 / (2 * q^2 * k^2))  — Gaussian rank weighting.
    Here we use the simpler 1/rank^W_RANK form.
    """
    weights = np.array([1.0 / (k ** W_RANK) for k in range(1, archive_size + 1)])
    weights /= weights.sum()
    return weights


def _sample_ant(archive, archive_weights_arr, xi):
    """
    Construct one ant's solution by sampling from the Gaussian mixture
    defined by the archive.

    For each parameter dimension d:
      1. Choose an archive entry l with probability archive_weights_arr[l].
      2. Compute σ_l = ξ • Σ_{j=1}^{k} |archive[j][d] - archive[l][d]| / (k-1)
      3. Sample: x_d = N(archive[l][d], σ_l^2)
    """
    k        = len(archive)
    values   = np.array([sol for sol, _ in archive])  # shape (k, 5)
    chosen_l = np.random.choice(k, p=archive_weights_arr)
    mean_vec = values[chosen_l]

    solution = []
    for d in range(5):
        # Gaussian spread proportional to archive diversity in dimension d
        if k > 1:
            sigma = xi * np.sum(np.abs(values[:, d] - mean_vec[d])) / (k - 1)
        else:
            lo, hi = BOUNDS[PARAM_NAMES[d]]
            sigma  = (hi - lo) * 0.1
        sigma = max(sigma, 1e-6)
        solution.append(np.random.normal(mean_vec[d], sigma))

    return _clip(solution)


def run_aco(points_xy_w, width, height):
    """
    Core ACO_R loop for continuous ellipse parameter optimisation.

    Parameters
    ----------
    points_xy_w : list of (x, y, intensity_weight) tuples
    width, height : image dimensions in pixels

    Returns
    -------
    best_params : [cx, cy, a, b, theta]  in pixel coordinates
    """
    # Initialise pheromone archive
    archive   = _init_archive(points_xy_w, width, height, ARCHIVE_SZ)
    arch_w    = _archive_weights(ARCHIVE_SZ)

    global_best_params, global_best_fit = archive[0]

    for iteration in range(N_ITERS):
        # ── Construct N_ANTS solutions ────────────────────────────────────────
        new_solutions = []
        for _ in range(N_ANTS):
            candidate = _sample_ant(archive, arch_w, XI)
            fit       = _fitness(candidate, points_xy_w)
            new_solutions.append((candidate, fit))

        # ── Keep top Q_BEST new solutions ────────────────────────────────────
        new_solutions.sort(key=lambda x: x[1], reverse=True)
        top_new = new_solutions[:Q_BEST]

        # ── Update archive: add top new, re-sort, truncate ───────────────────
        archive = sorted(archive + top_new,
                         key=lambda x: x[1], reverse=True)[:ARCHIVE_SZ]

        # ── Track global best ─────────────────────────────────────────────────
        if archive[0][1] > global_best_fit:
            global_best_params, global_best_fit = archive[0]

    # Final local refinement: tiny perturbation around best (5 extra ants)
    for _ in range(5 * N_ANTS):
        noise     = [np.random.normal(0, 0.05) for _ in range(5)]
        candidate = _clip([global_best_params[d] + noise[d] for d in range(5)])
        fit       = _fitness(candidate, points_xy_w)
        if fit > global_best_fit:
            global_best_params, global_best_fit = candidate, fit

    return global_best_params


